export function scaffoldDossier(ticketId, options = {}) {
  const id = String(ticketId ?? "").trim().toUpperCase();
  if (!id || !/^[A-Z0-9]+-[A-Z0-9_-]+$/.test(id)) {
    throw new Error(`Invalid ticket ID format: "${ticketId}". Expected format like "AGT-88" or "ETH-01".`);
  }

  const root = options.root ? path.resolve(options.root) : findRepoRoot();
  const tasksDir = path.join(root, ".agents", "tasks");
  const dossierDir = path.join(tasksDir, id);

  const title = options.title ?? "";
  const type = options.type ?? "tooling";
  const target = options.target ?? "0.05";
  const force = Boolean(options.force);
  const dryRun = Boolean(options.dryRun);

  const specContent = buildSpecTemplate({ id, title, type, target });
  const logContent = buildLogTemplate({ id });
  const acceptContent = buildAcceptTemplate({ id });

  const files = [
    { name: "spec.md", path: path.join(dossierDir, "spec.md"), content: specContent },
    { name: "log.md", path: path.join(dossierDir, "log.md"), content: logContent },
    { name: "accept.mjs", path: path.join(dossierDir, "accept.mjs"), content: acceptContent },
  ];

  // Preflight check: prevent accidental overwrite
  if (!dryRun) {
    if (fs.existsSync(dossierDir) && !force) {
      const existing = fs.readdirSync(dossierDir).filter((f) => files.some((x) => x.name === f));
      if (existing.length > 0) {
        throw new Error(
          `Dossier for ${id} already exists with files: ${existing.join(", ")}. Pass --force to overwrite.`
        );
      }
    }
    fs.mkdirSync(dossierDir, { recursive: true });
    for (const f of files) {
      fs.writeFileSync(f.path, f.content, "utf8");
    }
  }

  const result = {
    ticketId: id,
    dossierDir,
    dryRun,
    isTemplateOnly: true,
    warning: "Automated scaffolding generates unapproved templates only. An independent qualified reviewer must review and sign off before execution.",
    files: files.map((f) => ({
      name: f.name,
      relPath: path.relative(root, f.path).replace(/\\/g, "/"),
      bytes: Buffer.byteLength(f.content, "utf8"),
      sha256: sha256Lf(f.content),
    })),
  };

  return result;
}

// ---------------------------------------------------------------------------
// CLI Execution
// ---------------------------------------------------------------------------
function parseArgs(argv) {
  const flags = {};
  const positional = [];
  for (let i = 0; i < argv.length; i++) {
    const arg = argv[i];
    if (arg.startsWith("--")) {
      const key = arg.slice(2);
      const next = argv[i + 1];
      if (next === undefined || next.startsWith("--")) {
        flags[key] = true;
      } else {
        flags[key] = next;
        i++;
      }
    } else {
      positional.push(arg);
    }
  }
  return { flags, positional };
}

export function main(argv = process.argv.slice(2)) {
  const { flags, positional } = parseArgs(argv);
  const ticketId = positional[0];

  if (!ticketId || flags.help || flags.h) {
    console.log(`dossierScaffold v${SCAFFOLD_VERSION}: Scaffold task dossier templates

Usage:
  node dossierScaffold.mjs <TICKET-ID> [options]

Options:
  --title "<title>"    Human-readable ticket title
  --type <type>        Category (tooling, investigate, feature; default: tooling)
  --target <target>    Target tier (e.g. 0.05, 0.1; default: 0.05)
  --root <dir>         Repository root directory
  --force              Overwrite existing dossier files
  --dry-run            Generate in-memory without writing files
  --json               Output machine-readable JSON
`);
    process.exit(ticketId ? 0 : 1);
  }

  try {
    const res = scaffoldDossier(ticketId, {
      title: flags.title,
      type: flags.type,
      target: flags.target,
      root: flags.root,
      force: Boolean(flags.force),
      dryRun: Boolean(flags["dry-run"] || flags.dryRun),
    });

    if (flags.json) {
      console.log(JSON.stringify(res, null, 2));
    } else {
      console.log(`\n✅ Scaffolded task dossier for ${res.ticketId} in ${res.dossierDir}`);
      console.log(`⚠️  NOTE: ${res.warning}\n`);
      for (const f of res.files) {
        console.log(`  - ${f.relPath} (${f.bytes} B, sha256:${f.sha256.slice(0, 12)})`);
      }
      console.log(`\nNext step: Independent reviewer reviews spec.md and tailors accept.mjs before starting work.`);
    }
  } catch (err) {
    console.error(`❌ Error scaffolding dossier: ${err.message}`);
    process.exit(1);
  }
}

if (process.argv[1] && pathToFileURL(process.argv[1]).href === import.meta.url) {
  main();
}
