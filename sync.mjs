#!/usr/bin/env node
/**
 * Global (user-level) skills & rules, ONE source of truth for every AI tool on this machine.
 *
 *   ~/.agents/skills/<name>/   ->  ~/.claude/skills/<name>/          (Claude Code)
 *                              ->  ~/.gemini/config/skills/<name>/   (Antigravity)
 *   ~/.agents/rules/*.md       ->  ~/.gemini/config/rules/<file>     (Antigravity, always-on)
 *                              ->  ~/.claude/CLAUDE.md managed block (Claude Code, always-on)
 *   ~/.agents/agents/*.md      ->  ~/.claude/agents/<file>           (Claude Code subagents with pinned models)
 *   ~/.agents/hooks/claude-hooks.json -> ~/.claude/settings.json hooks (managed entries only)
 *
 * Copies (not symlinks) on purpose: both tools read them without extra permissions.
 * Generated copies carry a marker; stale generated copies are removed; hand-written files are never touched.
 * Run after editing anything in ~/.agents:   node ~/.agents/sync.mjs
 */
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const HOME = os.homedir();
const SRC = path.dirname(fileURLToPath(import.meta.url)); // the kit folder itself (normally ~/.agents)
const SRC_SKILLS = path.join(SRC, "skills");
const SRC_RULES = path.join(SRC, "rules");
const SKILL_TARGETS = [path.join(HOME, ".claude", "skills"), path.join(HOME, ".gemini", "config", "skills")];
const GEMINI_RULES = path.join(HOME, ".gemini", "config", "rules");
const CLAUDE_MD = path.join(HOME, ".claude", "CLAUDE.md");

const MARKER_FILE = ".generated-by-agents-sync";
const MARKER = "<!-- AUTO-GENERATED by ~/.agents/sync.mjs";
const BLOCK_BEGIN = "<!-- BEGIN ~/.agents/rules (AUTO-GENERATED by ~/.agents/sync.mjs, edit ~/.agents/rules instead) -->";
const BLOCK_END = "<!-- END ~/.agents/rules -->";

const report = { written: [], removed: [], skipped: [] };
const rel = (p) => "~/" + path.relative(HOME, p).replace(/\\/g, "/");
const read = (p) => fs.readFileSync(p, "utf-8").replace(/\r\n/g, "\n");
const dirs = (p) => (fs.existsSync(p) ? fs.readdirSync(p, { withFileTypes: true }).filter((d) => d.isDirectory()).map((d) => d.name) : []);

function writeIfChanged(file, content) {
  if (fs.existsSync(file) && read(file) === content) return;
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, content, "utf-8");
  report.written.push(rel(file));
}

/** Insert the marker comment right after the YAML frontmatter, so the skill still parses. */
function stampSkill(text, srcLabel) {
  const note = `${MARKER} from ${srcLabel}. Edit there, then run: node ~/.agents/sync.mjs -->`;
  const m = text.match(/^---\n[\s\S]*?\n---\n/);
  return m ? `${m[0]}\n${note}\n${text.slice(m[0].length)}` : `${note}\n\n${text}`;
}

function copySkillTree(srcDir, dstDir, name) {
  for (const entry of fs.readdirSync(srcDir, { withFileTypes: true })) {
    const s = path.join(srcDir, entry.name);
    const d = path.join(dstDir, entry.name);
    if (entry.isDirectory()) copySkillTree(s, d, name);
    else if (entry.name === "SKILL.md" && srcDir === path.join(SRC_SKILLS, name)) writeIfChanged(d, stampSkill(read(s), `~/.agents/skills/${name}`));
    else if (/\.(md|txt|json|ya?ml|mjs|js|ts|py|sh)$/i.test(entry.name)) writeIfChanged(d, read(s));
    else if (!fs.existsSync(d) || !fs.readFileSync(d).equals(fs.readFileSync(s))) {
      fs.mkdirSync(dstDir, { recursive: true });
      fs.copyFileSync(s, d);
      report.written.push(rel(d));
    }
  }
}

/** Remove files inside a generated copy that no longer exist in the source. */
function pruneTree(srcDir, dstDir) {
  for (const entry of fs.readdirSync(dstDir, { withFileTypes: true })) {
    if (entry.name === MARKER_FILE) continue;
    const s = path.join(srcDir, entry.name);
    const d = path.join(dstDir, entry.name);
    if (!fs.existsSync(s)) {
      fs.rmSync(d, { recursive: true, force: true });
      report.removed.push(rel(d));
    } else if (entry.isDirectory()) pruneTree(s, d);
  }
}

function syncSkills() {
  const names = dirs(SRC_SKILLS).filter((n) => fs.existsSync(path.join(SRC_SKILLS, n, "SKILL.md")));
  for (const target of SKILL_TARGETS) {
    for (const name of names) {
      const dst = path.join(target, name);
      if (fs.existsSync(dst) && !fs.existsSync(path.join(dst, MARKER_FILE))) {
        report.skipped.push(`${rel(dst)} (hand-written, left alone; delete it to let sync manage it)`);
        continue;
      }
      copySkillTree(path.join(SRC_SKILLS, name), dst, name);
      writeIfChanged(path.join(dst, MARKER_FILE), `Generated from ~/.agents/skills/${name}. Do not edit here.\n`);
      pruneTree(path.join(SRC_SKILLS, name), dst);
    }
    for (const name of dirs(target)) {
      const dst = path.join(target, name);
      if (!names.includes(name) && fs.existsSync(path.join(dst, MARKER_FILE))) {
        fs.rmSync(dst, { recursive: true, force: true });
        report.removed.push(rel(dst));
      }
    }
  }
}

function syncRules() {
  const files = fs.existsSync(SRC_RULES) ? fs.readdirSync(SRC_RULES).filter((f) => f.endsWith(".md")).sort() : [];

  // Antigravity: one generated file per rule.
  for (const f of files) {
    const dst = path.join(GEMINI_RULES, f);
    if (fs.existsSync(dst) && !read(dst).startsWith(MARKER)) {
      report.skipped.push(`${rel(dst)} (hand-written, left alone; delete it to let sync manage it)`);
      continue;
    }
    writeIfChanged(dst, `${MARKER} from ~/.agents/rules/${f}. Edit there, then run: node ~/.agents/sync.mjs -->\n\n${read(path.join(SRC_RULES, f))}`);
  }
  if (fs.existsSync(GEMINI_RULES)) {
    for (const f of fs.readdirSync(GEMINI_RULES)) {
      const dst = path.join(GEMINI_RULES, f);
      if (!files.includes(f) && f.endsWith(".md") && read(dst).startsWith(MARKER)) {
        fs.rmSync(dst);
        report.removed.push(rel(dst));
      }
    }
  }

  // Claude Code: a managed block inside ~/.claude/CLAUDE.md; anything outside the block is preserved.
  const body = files.map((f) => read(path.join(SRC_RULES, f)).trim()).join("\n\n");
  const block = files.length ? `${BLOCK_BEGIN}\n\n${body}\n\n${BLOCK_END}` : "";
  const current = fs.existsSync(CLAUDE_MD) ? read(CLAUDE_MD) : "";
  const re = new RegExp(`${BLOCK_BEGIN.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}[\\s\\S]*?${BLOCK_END.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}`);
  let next = re.test(current) ? current.replace(re, block) : block ? `${current.trimEnd()}${current.trim() ? "\n\n" : ""}${block}` : current;
  next = next.trim() ? `${next.trim()}\n` : "";
  if (next !== current) {
    if (next) writeIfChanged(CLAUDE_MD, next);
    else if (fs.existsSync(CLAUDE_MD)) (fs.rmSync(CLAUDE_MD), report.removed.push(rel(CLAUDE_MD)));
  }
}

/** Claude Code subagents (Antigravity has its own built-in subagents): ~/.agents/agents/*.md -> ~/.claude/agents/ */
function syncAgents() {
  const src = path.join(SRC, "agents");
  const dst = path.join(HOME, ".claude", "agents");
  const files = fs.existsSync(src) ? fs.readdirSync(src).filter((f) => f.endsWith(".md")) : [];
  for (const f of files) {
    const target = path.join(dst, f);
    if (fs.existsSync(target) && !read(target).includes(MARKER)) {
      report.skipped.push(`${rel(target)} (hand-written, left alone; delete it to let sync manage it)`);
      continue;
    }
    writeIfChanged(target, stampSkill(read(path.join(src, f)), `~/.agents/agents/${f}`));
  }
  if (fs.existsSync(dst)) {
    for (const f of fs.readdirSync(dst)) {
      const target = path.join(dst, f);
      if (!files.includes(f) && f.endsWith(".md") && read(target).includes(MARKER)) {
        fs.rmSync(target);
        report.removed.push(rel(target));
      }
    }
  }
}

/** Claude Code hooks: ~/.agents/hooks/claude-hooks.json -> hooks in ~/.claude/settings.json (managed entries only) */
function syncHooks() {
  const manifestFile = path.join(SRC, "hooks", "claude-hooks.json");
  if (!fs.existsSync(manifestFile)) return;
  const settingsFile = path.join(HOME, ".claude", "settings.json");
  const agentsPath = SRC.replace(/\\/g, "/");

  let manifest;
  try {
    manifest = JSON.parse(read(manifestFile).split("{{AGENTS}}").join(agentsPath));
  } catch (err) {
    report.skipped.push(`${rel(manifestFile)} (invalid JSON: ${err.message})`);
    return;
  }

  let settings = {};
  if (fs.existsSync(settingsFile)) {
    try {
      settings = JSON.parse(read(settingsFile));
    } catch (err) {
      report.skipped.push(`${rel(settingsFile)} (invalid JSON, left untouched: ${err.message})`);
      return;
    }
  }
  if (!settings || typeof settings !== "object" || Array.isArray(settings)) {
    report.skipped.push(`${rel(settingsFile)} (not a JSON object, left untouched)`);
    return;
  }

  const isManaged = (entry) =>
    Array.isArray(entry?.hooks) &&
    entry.hooks.some((h) => typeof h?.command === "string" && (h.command.includes("/.agents/hooks/") || h.command.includes("/.claude/hooks/context-watch.js")));

  const hooks = settings.hooks && typeof settings.hooks === "object" ? settings.hooks : {};
  for (const event of Object.keys(hooks)) {
    if (!Array.isArray(hooks[event])) continue;
    hooks[event] = hooks[event].filter((entry) => !isManaged(entry));
    if (!hooks[event].length) delete hooks[event];
  }
  for (const [event, entries] of Object.entries(manifest)) {
    hooks[event] = [...(hooks[event] || []), ...entries];
  }
  settings.hooks = hooks;

  writeIfChanged(settingsFile, JSON.stringify(settings, null, 2) + "\n");
}

syncSkills();
syncRules();
syncAgents();
syncHooks();

const line = (label, list) => list.length && console.log(`${label} (${list.length}):\n  ${list.join("\n  ")}`);
line("Written", report.written);
line("Removed", report.removed);
line("Skipped", report.skipped);
if (!report.written.length && !report.removed.length) console.log("Global agent skills & rules already in sync.");
