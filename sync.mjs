#!/usr/bin/env node
/**
 * Global (user-level) skills & rules, ONE source of truth for every AI tool on this machine.
 * The kit is the FuriousAISkill repo (git@github.com:CreativeAiTech/FuriousAISkill.git), cloned to ~/.agents.
 * Etherium's `yarn install` clones/fast-forwards it and runs this sync. After editing: node ~/.agents/sync.mjs, then commit + push.
 *
 *   skills/<name>/             ->  ~/.claude/skills/<name>/          (Claude Code)
 *                              ->  ~/.gemini/config/skills/<name>/   (Antigravity)
 *   rules/*.md                 ->  ~/.gemini/config/rules/<file>     (Antigravity, always-on)
 *                              ->  ~/.claude/CLAUDE.md managed block (Claude Code, always-on)
 *   agents/*.md                ->  ~/.claude/agents/<file>           (Claude Code subagents with pinned models)
 *   hooks/claude-hooks.json    -> ~/.claude/settings.json hooks (managed entries only)
 *   mcp/experimental/<name>.json -> ~/.claude.json top-level mcpServers (user scope; enabled features only,
 *                                managed entries only = command/args under <kit>/mcp/; atomic write, only when changed)
 *
 * EXPERIMENTAL features are opt-in: a skill whose frontmatter has `metadata.status: experimental`, and its hook
 * manifest hooks/experimental/<name>.json or mcp/experimental/<name>.json, are synced only when <name> is listed in ~/.agents/local.json (gitignored).
 *   node ~/.agents/sync.mjs --enable task-board     opt in (writes local.json, then syncs)
 *   node ~/.agents/sync.mjs --disable task-board    opt out (removes its generated skill copies and hooks)
 *   node ~/.agents/sync.mjs --list                  show experimental features and whether they are on
 *
 * Copies (not symlinks) on purpose: both tools read them without extra permissions.
 * Generated copies carry a marker; stale generated copies are removed; hand-written files are never touched.
 */
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const HOME = os.homedir();
const SRC = path.dirname(fileURLToPath(import.meta.url)); // the kit folder itself (the FuriousAISkill clone, ~/.agents)
const SRC_SKILLS = path.join(SRC, "skills");
const SRC_RULES = path.join(SRC, "rules");
const SKILL_TARGETS = [path.join(HOME, ".claude", "skills"), path.join(HOME, ".gemini", "config", "skills")];
const GEMINI_RULES = path.join(HOME, ".gemini", "config", "rules");
const CLAUDE_MD = path.join(HOME, ".claude", "CLAUDE.md");

const MARKER_FILE = ".generated-by-agents-sync";
const MARKER = "<!-- AUTO-GENERATED by agent-kit/sync.mjs";
const LEGACY_MARKER = "<!-- AUTO-GENERATED by ~/.agents/sync.mjs";
const isGenerated = (text) => text.startsWith(MARKER) || text.startsWith(LEGACY_MARKER);
const hasMarker = (text) => text.includes(MARKER) || text.includes(LEGACY_MARKER);
const BLOCK_BEGIN_PREFIX = "<!-- BEGIN agent-kit rules";
const BLOCK_BEGIN = `${BLOCK_BEGIN_PREFIX} (AUTO-GENERATED; edit ~/.agents (FuriousAISkill repo), then run: node ~/.agents/sync.mjs) -->`;
const EDIT_NOTE = "Edit ~/.agents (FuriousAISkill repo), then run: node ~/.agents/sync.mjs";
const BLOCK_END = "<!-- END agent-kit rules -->";
const LEGACY_BLOCK_BEGIN = "<!-- BEGIN ~/.agents/rules";
const LEGACY_BLOCK_END = "<!-- END ~/.agents/rules -->";

const report = { written: [], removed: [], skipped: [] };
const rel = (p) => "~/" + path.relative(HOME, p).replace(/\\/g, "/");
const read = (p) => fs.readFileSync(p, "utf-8").replace(/\r\n/g, "\n");
const dirs = (p) => (fs.existsSync(p) ? fs.readdirSync(p, { withFileTypes: true }).filter((d) => d.isDirectory()).map((d) => d.name) : []);

function writeIfChanged(file, content) {
  if (fs.existsSync(file) && read(file) === content) return;
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, content, "utf-8");
  report.written.push(rel(file));
}

/** Insert the marker comment right after the YAML frontmatter, so the skill still parses. */
function stampSkill(text, srcLabel) {
  const note = `${MARKER} from ${srcLabel}. ${EDIT_NOTE} -->`;
  const m = text.match(/^---\n[\s\S]*?\n---\n/);
  return m ? `${m[0]}\n${note}\n${text.slice(m[0].length)}` : `${note}\n\n${text}`;
}

function copySkillTree(srcDir, dstDir, name) {
  for (const entry of fs.readdirSync(srcDir, { withFileTypes: true })) {
    const s = path.join(srcDir, entry.name);
    const d = path.join(dstDir, entry.name);
    if (entry.isDirectory()) copySkillTree(s, d, name);
    else if (entry.name === "SKILL.md" && srcDir === path.join(SRC_SKILLS, name)) writeIfChanged(d, stampSkill(read(s), `skills/${name}`));
    else if (/\.(md|txt|json|ya?ml|mjs|js|ts|py|sh)$/i.test(entry.name)) writeIfChanged(d, read(s));
    else if (!fs.existsSync(d) || !fs.readFileSync(d).equals(fs.readFileSync(s))) {
      fs.mkdirSync(dstDir, { recursive: true });
      fs.copyFileSync(s, d);
      report.written.push(rel(d));
    }
  }
}

/** Remove files inside a generated copy that no longer exist in the source. */
function pruneTree(srcDir, dstDir) {
  for (const entry of fs.readdirSync(dstDir, { withFileTypes: true })) {
    if (entry.name === MARKER_FILE) continue;
    const s = path.join(srcDir, entry.name);
    const d = path.join(dstDir, entry.name);
    if (!fs.existsSync(s)) {
      fs.rmSync(d, { recursive: true, force: true });
      report.removed.push(rel(d));
    } else if (entry.isDirectory()) pruneTree(s, d);
  }
}

// ---------------------------------------------------------------------------
// Experimental opt-in (local.json is per machine and gitignored)
// ---------------------------------------------------------------------------
const LOCAL_FILE = path.join(SRC, "local.json");
const EXPERIMENTAL_HOOKS = path.join(SRC, "hooks", "experimental");
const EXPERIMENTAL_MCP = path.join(SRC, "mcp", "experimental");

function readLocal() {
  try {
    const data = JSON.parse(read(LOCAL_FILE));
    return { ...data, experimental: Array.isArray(data.experimental) ? data.experimental : [] };
  } catch {
    return { experimental: [] };
  }
}

/** `metadata.status: experimental` in a SKILL.md frontmatter. */
function isExperimentalSkill(name) {
  const fm = read(path.join(SRC_SKILLS, name, "SKILL.md")).match(/^---\n([\s\S]*?)\n---\n/)?.[1] ?? "";
  return /^\s+status:\s*["']?experimental["']?\s*$/m.test(fm);
}

function experimentalFeatures() {
  const skills = dirs(SRC_SKILLS).filter((n) => fs.existsSync(path.join(SRC_SKILLS, n, "SKILL.md")) && isExperimentalSkill(n));
  const hooks = fs.existsSync(EXPERIMENTAL_HOOKS) ? fs.readdirSync(EXPERIMENTAL_HOOKS).filter((f) => f.endsWith(".json")).map((f) => f.slice(0, -5)) : [];
  const mcp = fs.existsSync(EXPERIMENTAL_MCP) ? fs.readdirSync(EXPERIMENTAL_MCP).filter((f) => f.endsWith(".json")).map((f) => f.slice(0, -5)) : [];
  return [...new Set([...skills, ...hooks, ...mcp])].sort();
}

function handleOptInFlags(argv) {
  const features = experimentalFeatures();
  const local = readLocal();
  if (argv.includes("--list")) {
    if (!features.length) console.log("No experimental features in this kit.");
    for (const f of features) console.log(`${local.experimental.includes(f) ? "[on] " : "[off]"} ${f}`);
    process.exit(0);
  }
  for (const [flag, on] of [["--enable", true], ["--disable", false]]) {
    if (!argv.includes(flag)) continue;
    const name = argv[argv.indexOf(flag) + 1];
    if (!name || !features.includes(name)) {
      console.error(`${flag} needs one of: ${features.join(", ") || "(none available)"}`);
      process.exit(1);
    }
    const set = new Set(local.experimental);
    on ? set.add(name) : set.delete(name);
    local.experimental = [...set].sort();
    fs.writeFileSync(LOCAL_FILE, JSON.stringify(local, null, 2) + "\n", "utf-8");
    console.log(`${on ? "Enabled" : "Disabled"} experimental feature: ${name} (${path.basename(LOCAL_FILE)})`);
  }
  return new Set(local.experimental);
}

const ENABLED = handleOptInFlags(process.argv.slice(2));

function syncSkills() {
  const names = dirs(SRC_SKILLS).filter(
    (n) => fs.existsSync(path.join(SRC_SKILLS, n, "SKILL.md")) && (!isExperimentalSkill(n) || ENABLED.has(n))
  );
  for (const target of SKILL_TARGETS) {
    for (const name of names) {
      const dst = path.join(target, name);
      if (fs.existsSync(dst) && !fs.existsSync(path.join(dst, MARKER_FILE))) {
        report.skipped.push(`${rel(dst)} (hand-written, left alone; delete it to let sync manage it)`);
        continue;
      }
      copySkillTree(path.join(SRC_SKILLS, name), dst, name);
      writeIfChanged(path.join(dst, MARKER_FILE), `Generated from ~/.agents/skills/${name} (FuriousAISkill repo). Do not edit here.\n`);
      pruneTree(path.join(SRC_SKILLS, name), dst);
    }
    for (const name of dirs(target)) {
      const dst = path.join(target, name);
      if (!names.includes(name) && fs.existsSync(path.join(dst, MARKER_FILE))) {
        fs.rmSync(dst, { recursive: true, force: true });
        report.removed.push(rel(dst));
      }
    }
  }
}

function syncRules() {
  const files = fs.existsSync(SRC_RULES) ? fs.readdirSync(SRC_RULES).filter((f) => f.endsWith(".md")).sort() : [];

  // Antigravity: one generated file per rule.
  for (const f of files) {
    const dst = path.join(GEMINI_RULES, f);
    if (fs.existsSync(dst) && !isGenerated(read(dst))) {
      report.skipped.push(`${rel(dst)} (hand-written, left alone; delete it to let sync manage it)`);
      continue;
    }
    writeIfChanged(dst, `${MARKER} from rules/${f}. ${EDIT_NOTE} -->\n\n${read(path.join(SRC_RULES, f))}`);
  }
  if (fs.existsSync(GEMINI_RULES)) {
    for (const f of fs.readdirSync(GEMINI_RULES)) {
      const dst = path.join(GEMINI_RULES, f);
      if (!files.includes(f) && f.endsWith(".md") && isGenerated(read(dst))) {
        fs.rmSync(dst);
        report.removed.push(rel(dst));
      }
    }
  }

  // Claude Code: a managed block inside ~/.claude/CLAUDE.md; anything outside the block is preserved.
  const body = files.map((f) => read(path.join(SRC_RULES, f)).trim()).join("\n\n");
  const block = files.length ? `${BLOCK_BEGIN}\n\n${body}\n\n${BLOCK_END}` : "";
  const current = fs.existsSync(CLAUDE_MD) ? read(CLAUDE_MD) : "";
  const esc = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
  // Matches the current block (any BEGIN text with the prefix) and the legacy ~/.agents block, so exactly one block remains.
  const re = new RegExp(`${esc(BLOCK_BEGIN_PREFIX)}[^\\n]*?-->[\\s\\S]*?${esc(BLOCK_END)}|${esc(LEGACY_BLOCK_BEGIN)}[\\s\\S]*?${esc(LEGACY_BLOCK_END)}`, "g");
  let placed = false;
  let dropped = false;
  let next = re.test(current)
    ? current.replace(re, () => (placed ? ((dropped = true), "") : ((placed = true), block)))
    : block ? `${current.trimEnd()}${current.trim() ? "\n\n" : ""}${block}` : current;
  if (dropped) next = next.replace(/\n{3,}/g, "\n\n");
  next = next.trim() ? `${next.trim()}\n` : "";
  if (next !== current) {
    if (next) writeIfChanged(CLAUDE_MD, next);
    else if (fs.existsSync(CLAUDE_MD)) (fs.rmSync(CLAUDE_MD), report.removed.push(rel(CLAUDE_MD)));
  }
}

/** Claude Code subagents (Antigravity has its own built-in subagents): agents/*.md -> ~/.claude/agents/ */
function syncAgents() {
  const src = path.join(SRC, "agents");
  const dst = path.join(HOME, ".claude", "agents");
  const files = fs.existsSync(src) ? fs.readdirSync(src).filter((f) => f.endsWith(".md")) : [];
  for (const f of files) {
    const target = path.join(dst, f);
    if (fs.existsSync(target) && !hasMarker(read(target))) {
      report.skipped.push(`${rel(target)} (hand-written, left alone; delete it to let sync manage it)`);
      continue;
    }
    writeIfChanged(target, stampSkill(read(path.join(src, f)), `agents/${f}`));
  }
  if (fs.existsSync(dst)) {
    for (const f of fs.readdirSync(dst)) {
      const target = path.join(dst, f);
      if (!files.includes(f) && f.endsWith(".md") && hasMarker(read(target))) {
        fs.rmSync(target);
        report.removed.push(rel(target));
      }
    }
  }
}

/** Claude Code hooks: hooks/claude-hooks.json -> hooks in ~/.claude/settings.json (managed entries only) */
function syncHooks() {
  const manifestFile = path.join(SRC, "hooks", "claude-hooks.json");
  if (!fs.existsSync(manifestFile)) return;
  const settingsFile = path.join(HOME, ".claude", "settings.json");
  const agentsPath = SRC.replace(/\\/g, "/");

  let manifest;
  try {
    manifest = JSON.parse(read(manifestFile).split("{{AGENTS}}").join(agentsPath));
  } catch (err) {
    report.skipped.push(`${rel(manifestFile)} (invalid JSON: ${err.message})`);
    return;
  }

  let settings = {};
  if (fs.existsSync(settingsFile)) {
    try {
      settings = JSON.parse(read(settingsFile));
    } catch (err) {
      report.skipped.push(`${rel(settingsFile)} (invalid JSON, left untouched: ${err.message})`);
      return;
    }
  }
  if (!settings || typeof settings !== "object" || Array.isArray(settings)) {
    report.skipped.push(`${rel(settingsFile)} (not a JSON object, left untouched)`);
    return;
  }

  const managedPatterns = [`${agentsPath}/hooks/`, "/agent-kit/hooks/", "/.agents/hooks/", "/.claude/hooks/context-watch.js"];
  const isManaged = (entry) =>
    Array.isArray(entry?.hooks) &&
    entry.hooks.some((h) => typeof h?.command === "string" && managedPatterns.some((p) => h.command.replace(/\\/g, "/").includes(p)));

  const hooks = settings.hooks && typeof settings.hooks === "object" ? settings.hooks : {};
  for (const event of Object.keys(hooks)) {
    if (!Array.isArray(hooks[event])) continue;
    hooks[event] = hooks[event].filter((entry) => !isManaged(entry));
    if (!hooks[event].length) delete hooks[event];
  }
  const manifests = [manifest];
  for (const name of ENABLED) {
    const file = path.join(EXPERIMENTAL_HOOKS, `${name}.json`);
    if (!fs.existsSync(file)) continue;
    try {
      manifests.push(JSON.parse(read(file).split("{{AGENTS}}").join(agentsPath)));
    } catch (err) {
      report.skipped.push(`${rel(file)} (invalid JSON: ${err.message})`);
    }
  }
  for (const m of manifests) {
    for (const [event, entries] of Object.entries(m)) {
      hooks[event] = [...(hooks[event] || []), ...entries];
    }
  }
  settings.hooks = hooks;

  writeIfChanged(settingsFile, JSON.stringify(settings, null, 2) + "\n");
}

/** MCP servers: mcp/experimental/<name>.json (enabled features) -> ~/.claude.json mcpServers (managed entries only) */
function syncMcp() {
  const claudeJson = process.env.AGENTS_CLAUDE_JSON || path.join(HOME, ".claude.json"); // env override is for tests
  const agentsPath = SRC.replace(/\\/g, "/");

  const desired = {};
  for (const name of ENABLED) {
    const file = path.join(EXPERIMENTAL_MCP, `${name}.json`);
    if (!fs.existsSync(file)) continue;
    try {
      Object.assign(desired, JSON.parse(read(file).split("{{AGENTS}}").join(agentsPath)));
    } catch (err) {
      report.skipped.push(`${rel(file)} (invalid JSON: ${err.message})`);
    }
  }

  if (!fs.existsSync(claudeJson)) {
    if (Object.keys(desired).length) report.skipped.push(`${rel(claudeJson)} (missing, MCP servers not registered)`);
    return;
  }

  const isManaged = (entry) =>
    [entry?.command, ...(Array.isArray(entry?.args) ? entry.args : [])].some(
      (v) => typeof v === "string" && v.replace(/\\/g, "/").includes(`${agentsPath}/mcp/`)
    );

  /** Parse the file fresh and apply the desired state. Returns null when nothing changes. */
  const compute = () => {
    const raw = fs.readFileSync(claudeJson, "utf-8");
    const data = JSON.parse(raw);
    if (!data || typeof data !== "object" || Array.isArray(data)) throw new Error("not a JSON object");
    const before = JSON.stringify(data);
    const servers = data.mcpServers && typeof data.mcpServers === "object" && !Array.isArray(data.mcpServers) ? data.mcpServers : null;
    if (servers) {
      for (const [name, entry] of Object.entries(servers)) if (isManaged(entry) && !(name in desired)) delete servers[name];
    }
    for (const [name, entry] of Object.entries(desired)) {
      if (!data.mcpServers || typeof data.mcpServers !== "object" || Array.isArray(data.mcpServers)) data.mcpServers = {};
      const existing = data.mcpServers[name];
      if (existing && !isManaged(existing)) {
        report.skipped.push(`mcpServers.${name} in ${rel(claudeJson)} (user-defined entry, left untouched)`);
        continue;
      }
      data.mcpServers[name] = entry;
    }
    if (JSON.stringify(data) === before) return null;
    return JSON.stringify(data, null, 2) + (raw.endsWith("\n") ? "\n" : "");
  };

  let out;
  try {
    out = compute();
    if (out === null) return;
    out = compute(); // re-read right before writing: Claude Code also rewrites this file
    if (out === null) return;
  } catch (err) {
    report.skipped.push(`${rel(claudeJson)} (invalid JSON, left untouched: ${err.message})`);
    return;
  }
  const tmp = `${claudeJson}.${process.pid}.tmp`;
  fs.writeFileSync(tmp, out, "utf-8");
  fs.renameSync(tmp, claudeJson);
  report.written.push(`${rel(claudeJson)} (mcpServers)`);
}

syncSkills();
syncRules();
syncAgents();
syncHooks();
syncMcp();

const line = (label, list) => list.length && console.log(`${label} (${list.length}):\n  ${list.join("\n  ")}`);
line("Written", report.written);
line("Removed", report.removed);
line("Skipped", report.skipped);
if (!report.written.length && !report.removed.length) console.log("Global agent skills & rules already in sync.");
